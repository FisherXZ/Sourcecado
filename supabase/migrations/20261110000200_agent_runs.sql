-- Agent Run store (migration slice S02). Head schema of `agent_runs.db` at
-- SQLite schema version 2. `backend/coworker/agent_run_repository.py` reads and
-- writes these tables.
--
-- Every row belongs to one user. Run ids and effect ids are unique for one
-- user, so each key starts with `user_id`.
--
-- Every text column uses the "C" collation. SQLite compares text as bytes;
-- the Postgres default is a language collation. Byte order keeps ORDER BY,
-- range comparisons, and keys the same as before. Timestamps stay
-- fixed-width UTC text, so string order is time order.
--
-- `insert_order` replaces the SQLite `rowid`. The repository uses it only to
-- break ties between rows with the same timestamp.

create table agent_runs (
  user_id uuid not null references auth.users(id) on delete cascade,
  run_id text collate "C" not null,
  insert_order bigint generated by default as identity,
  session_id text collate "C" not null,
  person_id text collate "C",
  parent_run_id text collate "C",
  trigger text collate "C" not null,
  goal_fingerprint text collate "C" not null,
  provider_model_id text collate "C",
  current_state text collate "C" not null,
  version bigint not null default 0,
  checkpoint_sequence bigint not null default 0,
  approval_ids text collate "C" not null default '[]',
  source_refs text collate "C" not null default '[]',
  artifact_refs text collate "C" not null default '[]',
  usage text collate "C" not null default '{}',
  terminal_result text collate "C",
  lease_owner text collate "C",
  lease_owner_host text collate "C",
  lease_owner_pid bigint,
  lease_expires_at text collate "C",
  created_at text collate "C" not null,
  updated_at text collate "C" not null,
  finished_at text collate "C",
  primary key (user_id, run_id)
);

create index agent_runs_session_created
  on agent_runs (user_id, session_id, created_at);
create index agent_runs_live_lease
  on agent_runs (user_id, lease_expires_at) where lease_owner is not null;

create table agent_run_checkpoints (
  user_id uuid not null references auth.users(id) on delete cascade,
  run_id text collate "C" not null,
  sequence bigint not null,
  kind text collate "C" not null,
  state text collate "C" not null,
  payload text collate "C" not null,
  created_at text collate "C" not null,
  primary key (user_id, run_id, sequence),
  foreign key (user_id, run_id) references agent_runs (user_id, run_id)
);

-- The external-effect fence. The rules below are also enforced in
-- `AgentRunRepository`. They are repeated here so that a raw SQL edit, a new
-- method, or a bug in one of those paths still hits a wall.
--
-- The status and replay class lists must match `coworker/agent_run_approval.py`.
-- `tests/test_agent_run_effect_fence.py` checks that they do.
create table agent_run_effects (
  user_id uuid not null references auth.users(id) on delete cascade,
  effect_id text collate "C" not null,
  insert_order bigint generated by default as identity,
  run_id text collate "C" not null,
  tool_name text collate "C" not null,
  tool_call_id text collate "C",
  approval_id text collate "C",
  replay_class text collate "C" not null,
  arguments_fingerprint text collate "C" not null,
  status text collate "C" not null,
  dispatched_by text collate "C" not null,
  dispatched_at text collate "C" not null,
  settled_at text collate "C",
  outcome_ref text collate "C",
  reason text collate "C",
  resolved_by text collate "C",
  resolved_note text collate "C",
  resolved_at text collate "C",
  primary key (user_id, effect_id),
  foreign key (user_id, run_id) references agent_runs (user_id, run_id),
  constraint agent_run_effects_status check (status in (
    'abandoned', 'ambiguous', 'dispatched', 'failed',
    'resolved_failed', 'resolved_succeeded', 'succeeded'
  )),
  constraint agent_run_effects_replay_class check (
    replay_class in ('consequential', 'safe')
  ),
  -- A person's verdict cannot exist in this table without the person.
  constraint agent_run_effects_operator_named check (
    (status in ('abandoned', 'resolved_failed', 'resolved_succeeded'))
      = (resolved_by is not null)
  )
);

create index agent_run_effects_by_run
  on agent_run_effects (user_id, run_id, status);
create index agent_run_effects_open
  on agent_run_effects (user_id, status, dispatched_at);

-- One function for the four refusals. The trigger passes the message.
-- SQLSTATE 23000 makes the driver raise an IntegrityError, as SQLite's
-- RAISE(ABORT) did.
create function agent_run_effects_refuse() returns trigger
language plpgsql as $$
begin
  raise exception '%', tg_argv[0] using errcode = '23000';
end;
$$;

create trigger agent_run_effects_open_as_dispatched
  before insert on agent_run_effects
  for each row when (new.status <> 'dispatched')
  execute function agent_run_effects_refuse(
    'an external effect record opens as dispatched');

create trigger agent_run_effects_quarantine_is_operator_only
  before update of status on agent_run_effects
  for each row when (
    old.status = 'ambiguous'
    and new.status not in (
      'abandoned', 'ambiguous', 'resolved_failed', 'resolved_succeeded')
  )
  execute function agent_run_effects_refuse(
    'a quarantined external effect is settled by a person, never by code');

create trigger agent_run_effects_settled_is_final
  before update of status on agent_run_effects
  for each row when (
    old.status in (
      'abandoned', 'failed', 'resolved_failed', 'resolved_succeeded', 'succeeded')
    and new.status <> old.status
  )
  execute function agent_run_effects_refuse(
    'a settled external effect never changes outcome');

-- An effect row is never deleted by code. The one exception is the deletion of
-- the user who owns it: `on delete cascade` from auth.users must still work.
-- During that cascade the user row is already gone.
create function agent_run_effects_refuse_delete() returns trigger
language plpgsql as $$
begin
  if exists (select 1 from auth.users where id = old.user_id) then
    raise exception
      'an external effect record is evidence that something left the machine'
      using errcode = '23000';
  end if;
  return old;
end;
$$;

create trigger agent_run_effects_are_never_deleted
  before delete on agent_run_effects
  for each row execute function agent_run_effects_refuse_delete();
