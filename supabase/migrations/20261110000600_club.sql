-- Conversation store (migration slice S06). Was `club.db`.
--
-- Head schema of `coworker/store.py`, with `user_id` on every table.
-- The JSONL transcripts, the event logs, and the `memory/` Markdown mirror
-- stay on disk next to the state directory until slice S09.
--
-- Two choices keep SQLite behavior:
-- * Every text column is `collate "C"`. SQLite compares text bytewise. The
--   database default collation does not, and the store compares ISO
--   timestamps as text (`expires_at <= now`, `next_run_at <= now`).
-- * A column that SQLite filled with CURRENT_TIMESTAMP gets the same text
--   shape here: `YYYY-MM-DD HH:MM:SS` in UTC.
-- `sessions.seq` and `inbox.seq` stand in for the SQLite rowid. The store
-- uses them only to break ties in an order, the way SQLite used the rowid.

create table public.sessions (
    user_id uuid not null references auth.users(id) on delete cascade,
    session_id text collate "C" not null,
    title text collate "C",
    n_msgs bigint default 0,
    pinned bigint not null default 0,
    opened_at text collate "C"
        default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at text collate "C"
        default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    seq bigint generated by default as identity,
    primary key (user_id, session_id)
);

create table public.memories (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    content text collate "C" not null,
    created_at text collate "C"
        default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    category text collate "C" not null default 'unclassified',
    classification_status text collate "C" not null default 'needs_review',
    person_id text collate "C",
    session_id text collate "C",
    source_ref text collate "C",
    updated_at text collate "C",
    fresh_until text collate "C",
    sensitivity text collate "C" not null default 'standard',
    claim_key text collate "C"
);
create index memories_user_id on public.memories (user_id, id);

create table public.jobs (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    cron text collate "C" not null,
    prompt text collate "C" not null,
    created_at text collate "C"
        default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    next_run_at text collate "C",
    name text collate "C",
    template_id text collate "C",
    cadence text collate "C"
);
create index jobs_user_id on public.jobs (user_id, id);

create table public.runs (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    job_id bigint not null,
    status text collate "C" not null,
    result text collate "C",
    created_at text collate "C"
        default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    started_at text collate "C",
    finished_at text collate "C",
    duration_ms bigint,
    summary text collate "C",
    artifacts text collate "C",
    session_id text collate "C",
    waiting_approval_count bigint default 0,
    -- Count of events already in the reused sched-{job_id} event file when
    -- this run started. The restart reconciler ignores those events.
    event_offset bigint not null default 0
);
create index runs_user_id on public.runs (user_id, id);
create index runs_user_status on public.runs (user_id, status);

create table public.settings (
    user_id uuid not null references auth.users(id) on delete cascade,
    key text collate "C" not null,
    value text collate "C" not null,
    primary key (user_id, key)
);

create table public.inbox (
    user_id uuid not null references auth.users(id) on delete cascade,
    id text collate "C" not null,
    kind text collate "C" not null,
    name text collate "C" not null,
    arguments text collate "C" not null,
    state text collate "C" not null,
    decision text collate "C",
    actor text collate "C",
    requested_at text collate "C",
    resolved_at text collate "C",
    scope text collate "C" default 'once',
    execution_status text collate "C" default 'pending',
    execution_error text collate "C",
    execution_claimant text collate "C",
    execution_result text collate "C",
    expires_at text collate "C",
    reason text collate "C",
    session_id text collate "C",
    run_id text collate "C",
    message_id text collate "C",
    part_id text collate "C",
    recovery_command_id text collate "C",
    original_call_id text collate "C",
    resource text collate "C",
    created_at text collate "C"
        default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    seq bigint generated by default as identity,
    primary key (user_id, id)
);
create index inbox_user_state on public.inbox (user_id, state);

create table public.chat_queue (
    user_id uuid not null references auth.users(id) on delete cascade,
    session_id text collate "C" not null,
    id text collate "C" not null,
    text text collate "C" not null,
    position bigint not null,
    state text collate "C" not null,
    error text collate "C",
    created_at text collate "C" not null,
    updated_at text collate "C" not null,
    primary key (user_id, session_id, id)
);
create index chat_queue_session_position
    on public.chat_queue (user_id, session_id, position);

create table public.queue_commands (
    user_id uuid not null references auth.users(id) on delete cascade,
    session_id text collate "C" not null,
    command_id text collate "C" not null,
    command_type text collate "C" not null,
    item_id text collate "C",
    acknowledgement text collate "C" not null,
    created_at text collate "C" not null,
    primary key (user_id, session_id, command_id)
);

create table public.queue_sessions (
    user_id uuid not null references auth.users(id) on delete cascade,
    session_id text collate "C" not null,
    paused bigint not null default 0,
    updated_at text collate "C" not null,
    primary key (user_id, session_id)
);

create table public.recovery_commands (
    user_id uuid not null references auth.users(id) on delete cascade,
    session_id text collate "C" not null,
    command_id text collate "C" not null,
    created_at text collate "C" not null,
    primary key (user_id, session_id, command_id)
);
